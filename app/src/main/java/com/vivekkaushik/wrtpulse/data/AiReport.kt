package com.vivekkaushik.wrtpulse.data

import com.vivekkaushik.wrtpulse.ops.Finding
import com.vivekkaushik.wrtpulse.ops.HealthScore
import com.vivekkaushik.wrtpulse.ops.Severity
import com.vivekkaushik.wrtpulse.ops.TemporalStats

/**
 * The report the analysis screen exports: health, local findings, the 60-second sample and the
 * provider's answer, arranged so it reads the same on a phone, in an editor and on paper.
 *
 * Two invariants survive every format. Secrets never get in — the payload they came from was
 * already redacted, and the report is built from the same redacted data. And [sanitize] can
 * strip what is left that identifies a network: MAC addresses lose their last three octets,
 * public IPv4s and global IPv6s become x's, private addresses stay because a report about a
 * LAN that cannot mention the LAN is useless.
 */
data class ReportParts(
    val routerLabel: String,
    val generatedAt: String,
    val health: HealthScore?,
    val temporal: TemporalStats?,
    val findings: List<Finding>,
    val question: String,
    val answer: String?,
)

object AiReport {

    /** The name prefix for exported files; the timestamp suffix is added by the caller. */
    const val FILE_PREFIX = "WrtPulse-report"

    /** Markdown — for editors, issue trackers and pasting into chat. */
    fun markdown(parts: ReportParts, sanitized: Boolean): String = sanitizeIfNeeded(buildString {
        append("# WrtPulse — Router analysis report\n\n")
        append("**Router:** ${parts.routerLabel.ifBlank { "unknown" }}\n")
        append("**Generated:** ${parts.generatedAt}\n")
        if (parts.question.isNotBlank()) append("**Question:** ${parts.question}\n")

        parts.health?.let { h ->
            append("\n## Network health\n\n")
            append("**Overall: ${h.overall}/100 — ${h.grade.label}**\n\n")
            append("| Wi-Fi | Mesh | Performance | Security |\n")
            append("|---|---|---|---|\n")
            append("| ${h.wifi} | ${h.mesh ?: "—"} | ${h.performance} | ${h.security} |\n")
        }

        parts.temporal?.let { t ->
            append("\n## 60-second sample\n\n")
            t.summaryLines().forEach { append("- $it\n") }
        }

        if (parts.findings.isNotEmpty()) {
            append("\n## Local findings\n")
            parts.findings.forEach { f ->
                append("\n### ${f.severity} — ${f.title}\n")
                append("- Evidence: ${f.evidence}\n")
                append("- Verify with: `${f.command}`\n")
            }
        } else {
            append("\n## Local findings\n\nNone — the phone-side rules found nothing worth flagging.\n")
        }

        parts.answer?.let { a ->
            append("\n## AI analysis\n\n")
            append(a.trimIndent().trim())
            append("\n")
        }

        append("\n---\n")
        append(
            if (sanitized) "Generated by WrtPulse. Secrets were redacted on the phone; this copy also " +
                "masks MAC addresses and public addresses."
            else "Generated by WrtPulse. Secrets were redacted on the phone before analysis.",
        )
        append("\n")
    }, sanitized)

    /** Plain text — for terminals, email bodies and anything that chews on backticks. */
    fun text(parts: ReportParts, sanitized: Boolean): String = sanitizeIfNeeded(buildString {
        append("WRTPLUSE ROUTER ANALYSIS REPORT\n\n")
        append("Router: ${parts.routerLabel.ifBlank { "unknown" }}\n")
        append("Generated: ${parts.generatedAt}\n")
        if (parts.question.isNotBlank()) append("Question: ${parts.question}\n")

        parts.health?.let { h ->
            append("\nNETWORK HEALTH\n")
            append("Overall: ${h.overall}/100 — ${h.grade.label}\n")
            append("Wi-Fi: ${h.wifi}   Mesh: ${h.mesh ?: "—"}   Performance: ${h.performance}   Security: ${h.security}\n")
        }

        parts.temporal?.let { t ->
            append("\n60-SECOND SAMPLE\n")
            t.summaryLines().forEach { append("$it\n") }
        }

        append("\nLOCAL FINDINGS\n")
        if (parts.findings.isEmpty()) {
            append("None — the phone-side rules found nothing worth flagging.\n")
        } else {
            parts.findings.forEach { f ->
                append("\n[${f.severity}] ${f.title}\n")
                append("  Evidence: ${f.evidence}\n")
                append("  Verify with: ${f.command}\n")
            }
        }

        parts.answer?.let { a ->
            append("\nAI ANALYSIS\n\n")
            append(a.trim())
            append("\n")
        }

        append("\n")
        append(
            if (sanitized) "Generated by WrtPulse. Secrets redacted on the phone; this copy also masks " +
                "MAC and public addresses."
            else "Generated by WrtPulse. Secrets were redacted on the phone before analysis.",
        )
        append("\n")
    }, sanitized)

    /**
     * Masks what identifies a network without hollowing the report out: MACs keep their OUI
     * and lose the rest, public IPv4s and global IPv6s become placeholders, private and
     * link-local addresses survive because they are what the findings are about.
     */
    fun sanitize(report: String): String = report
        .replace(MAC) { m ->
            val octets = m.value.split(':')
            octets.take(3).joinToString(":") + ":XX:XX:XX"
        }
        .replace(IPV4) { m ->
            if (isPrivateV4(m.value)) m.value else "x.x.x.x"
        }
        .replace(GLOBAL_IPV6) { m ->
            if (isLocalV6(m.value)) m.value else "<ipv6>"
        }

    private fun sanitizeIfNeeded(report: String, sanitized: Boolean) =
        if (sanitized) sanitize(report) else report

    private val MAC = Regex("""\b(?:[0-9A-Fa-f]{2}:){5}[0-9A-Fa-f]{2}\b""")
    private val IPV4 = Regex("""\b(?:\d{1,3}\.){3}\d{1,3}\b""")

    /**
     * IPv6 is matched loosely (colon-hex words of at least 5 groups) and filtered to globals;
     * `fe80::`, `fc/fd00::` ULA and `::1` are local by definition.
     */
    private val GLOBAL_IPV6 = Regex("""\b(?:[0-9A-Fa-f]{1,4}:){4,7}[0-9A-Fa-f]{0,4}\b""")

    private fun isPrivateV4(ip: String): Boolean {
        val parts = ip.split('.').mapNotNull { it.toIntOrNull() }
        if (parts.size != 4) return true
        val (a, b) = parts
        return a == 10 || a == 127 || a == 0 || (a == 172 && b in 16..31) ||
            (a == 192 && b == 168) || (a == 169 && b == 254) || a >= 224
    }

    private fun isLocalV6(ip: String): Boolean {
        val h = ip.lowercase()
        return h == "::1" || h.startsWith("fe80:") || h.startsWith("fc") || h.startsWith("fd") || h.startsWith("::ffff:127.")
    }

    /** The severity tone the finding rows and the report agree on. */
    fun severityTag(severity: Severity): String = when (severity) {
        Severity.HIGH -> "HIGH"
        Severity.MED -> "MED"
        Severity.LOW -> "LOW"
    }
}
